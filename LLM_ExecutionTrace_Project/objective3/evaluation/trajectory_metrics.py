"""
Objective 3 — Descriptive Metrics.

Calculates architecture-level descriptive statistics across a batch
of TaskTrajectories.

Produces a RunSummary model.

IMPORTANT: This does NOT implement Objective 4 comparative statistical
tests. It merely summarizes the raw data generated by the architecture.
"""

from __future__ import annotations

import statistics
from typing import List

from objective3.models import (
    FinalTaskResult,
    RepairOutcome,
    RunSummary,
    TaskTrajectory,
)


class TrajectoryMetrics:
    """Computes descriptive metrics from executed trajectories."""

    def compute_summary(self, trajectories: List[TaskTrajectory]) -> RunSummary:
        """Compute the RunSummary from a list of trajectories."""
        total = len(trajectories)
        if total == 0:
            return RunSummary()

        initially_passing = 0
        entered_repair = 0
        successfully_repaired = 0
        max_iter = 0
        same_error = 0
        new_error = 0
        regressions = 0
        oscillations = 0
        failures = 0

        iteration_counts = []

        for t in trajectories:
            if t.initial_status == "Passed":
                initially_passing += 1
                continue

            entered_repair += 1
            if t.successful:
                successfully_repaired += 1
            if t.termination_reason and t.termination_reason.name == "MAX_ITERATIONS":
                max_iter += 1

            if t.regression_detected:
                regressions += 1
            if t.oscillation_detected:
                oscillations += 1
            if t.analysis_failure:
                failures += 1

            iteration_counts.append(t.iterations_used)

            # Count outcomes across all iterations
            for it in t.iterations:
                if it.controller_decision:
                    if it.controller_decision.outcome == RepairOutcome.SAME_ERROR:
                        same_error += 1
                    elif it.controller_decision.outcome == RepairOutcome.NEW_ERROR:
                        new_error += 1

        mean_iters = statistics.mean(iteration_counts) if iteration_counts else 0.0
        median_iters = float(statistics.median(iteration_counts)) if iteration_counts else 0.0

        return RunSummary(
            total_tasks=total,
            initially_passing=initially_passing,
            entered_repair=entered_repair,
            successfully_repaired=successfully_repaired,
            reached_max_iterations=max_iter,
            same_error_stalls=same_error,
            new_error_transitions=new_error,
            regressions_detected=regressions,
            oscillations_detected=oscillations,
            analysis_failures=failures,
            mean_iterations=mean_iters,
            median_iterations=median_iters,
        )

    def extract_final_results(self, trajectories: List[TaskTrajectory]) -> List[FinalTaskResult]:
        """Convert deep trajectories into flat FinalTaskResult objects for Objective 4."""
        results = []
        for t in trajectories:
            same_error = 0
            new_error = 0
            escalations = 0
            invalid = 0
            strategy = "LOCAL_MODIFICATION"

            for it in t.iterations:
                if it.controller_decision:
                    out = it.controller_decision.outcome
                    if out == RepairOutcome.SAME_ERROR:
                        same_error += 1
                    elif out == RepairOutcome.NEW_ERROR:
                        new_error += 1
                    elif out == RepairOutcome.INVALID_REPAIR:
                        invalid += 1
                    
                    if it.controller_decision.escalated:
                        escalations += 1
                strategy = it.repair_strategy_used.value

            exec_attempts = t.iterations_used + 1  # includes iter 0

            res = FinalTaskResult(
                task_id=t.task_id,
                trace_id=t.trace_id,
                benchmark=t.benchmark,
                successful=t.successful,
                initial_status=t.initial_status,
                final_status=t.final_status,
                termination_reason=t.termination_reason.name if t.termination_reason else None,
                iterations_used=t.iterations_used,
                initial_error_category=t.initial_error_category,
                final_error_category=t.final_error_category,
                regression_detected=t.regression_detected,
                oscillation_detected=t.oscillation_detected,
                diagnosis_status=t.diagnosis_status,
                analysis_failure=t.analysis_failure,
                repair_attempts=t.iterations_used,
                execution_attempts=exec_attempts,
                same_error_stalls=same_error,
                new_error_transitions=new_error,
                escalations=escalations,
                strategy_at_termination=strategy,
            )
            results.append(res)
        return results
